BEGIN
    FOR tabla IN (
        SELECT 'MOVIMIENTO_INVENTARIO' nombre FROM DUAL UNION ALL
        SELECT 'DETALLE_VENTA' FROM DUAL UNION ALL
        SELECT 'DETALLE_COMPRA' FROM DUAL UNION ALL
        SELECT 'ASISTENCIA' FROM DUAL UNION ALL
        SELECT 'VENTA' FROM DUAL UNION ALL
        SELECT 'COMPRA' FROM DUAL UNION ALL
        SELECT 'GASTO' FROM DUAL UNION ALL
        SELECT 'PRESUPUESTO_GASTO' FROM DUAL UNION ALL
        SELECT 'CATEGORIA_GASTO' FROM DUAL UNION ALL
        SELECT 'PRODUCTO' FROM DUAL UNION ALL
        SELECT 'EMPLEADOS' FROM DUAL UNION ALL
        SELECT 'EMPLEADO' FROM DUAL UNION ALL
        SELECT 'DEPARTAMENTO' FROM DUAL UNION ALL
        SELECT 'CLIENTE' FROM DUAL UNION ALL
        SELECT 'PROVEEDOR' FROM DUAL
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || tabla.nombre || ' CASCADE CONSTRAINTS';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN RAISE; END IF;
        END;
    END LOOP;
END;
/

CREATE TABLE CLIENTE (
    ID_CLIENTE       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRES          VARCHAR2(100) NOT NULL,
    APELLIDOS        VARCHAR2(100) NOT NULL,
    TELEFONO         VARCHAR2(30),
    EMAIL            VARCHAR2(150),
    DIRECCION        VARCHAR2(250),
    FECHA_REGISTRO   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE PROVEEDOR (
    ID_PROVEEDOR     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RAZON_SOCIAL     VARCHAR2(150) NOT NULL,
    TELEFONO         VARCHAR2(30),
    EMAIL            VARCHAR2(150),
    DIRECCION        VARCHAR2(250),
    FECHA_REGISTRO   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_PROVEEDOR PRIMARY KEY (ID_PROVEEDOR),
    CONSTRAINT UQ_PROVEEDOR_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE DEPARTAMENTO (
    ID_DEPARTAMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE          VARCHAR2(100) NOT NULL,
    DESCRIPCION     VARCHAR2(250),
    CONSTRAINT PK_DEPARTAMENTO PRIMARY KEY (ID_DEPARTAMENTO),
    CONSTRAINT UQ_DEPARTAMENTO_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE EMPLEADO (
    ID_EMPLEADO     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_DEPARTAMENTO NUMBER NOT NULL,
    NOMBRES         VARCHAR2(100) NOT NULL,
    APELLIDOS       VARCHAR2(100) NOT NULL,
    CARGO           VARCHAR2(100) NOT NULL,
    EMAIL           VARCHAR2(150),
    TELEFONO        VARCHAR2(30),
    FECHA_INGRESO   DATE NOT NULL,
    SALARIO         NUMBER(14, 2),
    CONSTRAINT PK_EMPLEADO PRIMARY KEY (ID_EMPLEADO),
    CONSTRAINT FK_EMPLEADO_DEPARTAMENTO FOREIGN KEY (ID_DEPARTAMENTO)
        REFERENCES DEPARTAMENTO (ID_DEPARTAMENTO),
    CONSTRAINT UQ_EMPLEADO_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE PRODUCTO (
    ID_PRODUCTO       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO            VARCHAR2(40) NOT NULL,
    NOMBRE            VARCHAR2(150) NOT NULL,
    DESCRIPCION       VARCHAR2(250),
    PRECIO_VENTA      NUMBER(14, 2) NOT NULL,
    COSTO_REFERENCIA  NUMBER(14, 2) DEFAULT 0 NOT NULL,
    STOCK             NUMBER(12, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT UQ_PRODUCTO_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE VENTA (
    ID_VENTA     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CLIENTE   NUMBER NOT NULL,
    ID_EMPLEADO  NUMBER NOT NULL,
    FECHA_VENTA  DATE DEFAULT SYSDATE NOT NULL,
    TOTAL        NUMBER(14, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_VENTA PRIMARY KEY (ID_VENTA),
    CONSTRAINT FK_VENTA_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_VENTA_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES EMPLEADO (ID_EMPLEADO)
);

CREATE TABLE DETALLE_VENTA (
    ID_DETALLE_VENTA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_VENTA         NUMBER NOT NULL,
    ID_PRODUCTO      NUMBER NOT NULL,
    CANTIDAD         NUMBER(12, 2) NOT NULL,
    PRECIO_UNITARIO  NUMBER(14, 2) NOT NULL,
    DESCUENTO       NUMBER(14, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DETALLE_VENTA PRIMARY KEY (ID_DETALLE_VENTA),
    CONSTRAINT FK_DETALLE_VENTA_VENTA FOREIGN KEY (ID_VENTA)
        REFERENCES VENTA (ID_VENTA) ON DELETE CASCADE,
    CONSTRAINT FK_DETALLE_VENTA_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO),
    CONSTRAINT UQ_DETALLE_VENTA_PRODUCTO UNIQUE (ID_VENTA, ID_PRODUCTO)
);

CREATE TABLE COMPRA (
    ID_COMPRA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PROVEEDOR   NUMBER NOT NULL,
    ID_EMPLEADO    NUMBER NOT NULL,
    NUMERO_FACTURA VARCHAR2(50) NOT NULL,
    FECHA_COMPRA   DATE DEFAULT SYSDATE NOT NULL,
    TOTAL          NUMBER(14, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_COMPRA PRIMARY KEY (ID_COMPRA),
    CONSTRAINT FK_COMPRA_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR)
        REFERENCES PROVEEDOR (ID_PROVEEDOR),
    CONSTRAINT FK_COMPRA_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES EMPLEADO (ID_EMPLEADO),
    CONSTRAINT UQ_COMPRA_FACTURA UNIQUE (ID_PROVEEDOR, NUMERO_FACTURA)
);

CREATE TABLE DETALLE_COMPRA (
    ID_DETALLE_COMPRA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_COMPRA         NUMBER NOT NULL,
    ID_PRODUCTO       NUMBER NOT NULL,
    CANTIDAD          NUMBER(12, 2) NOT NULL,
    COSTO_UNITARIO    NUMBER(14, 2) NOT NULL,
    DESCUENTO         NUMBER(14, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_DETALLE_COMPRA PRIMARY KEY (ID_DETALLE_COMPRA),
    CONSTRAINT FK_DETALLE_COMPRA_COMPRA FOREIGN KEY (ID_COMPRA)
        REFERENCES COMPRA (ID_COMPRA) ON DELETE CASCADE,
    CONSTRAINT FK_DETALLE_COMPRA_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO),
    CONSTRAINT UQ_DETALLE_COMPRA_PRODUCTO UNIQUE (ID_COMPRA, ID_PRODUCTO)
);

CREATE TABLE MOVIMIENTO_INVENTARIO (
    ID_MOVIMIENTO    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PRODUCTO      NUMBER NOT NULL,
    ID_EMPLEADO      NUMBER NOT NULL,
    TIPO_MOVIMIENTO  VARCHAR2(10) NOT NULL,
    CANTIDAD         NUMBER(12, 2) NOT NULL,
    FECHA_MOVIMIENTO DATE DEFAULT SYSDATE NOT NULL,
    ID_COMPRA        NUMBER,
    ID_VENTA         NUMBER,
    OBSERVACION      VARCHAR2(250),
    CONSTRAINT PK_MOVIMIENTO_INVENTARIO PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_MOVIMIENTO_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
        REFERENCES PRODUCTO (ID_PRODUCTO),
    CONSTRAINT FK_MOVIMIENTO_EMPLEADO FOREIGN KEY (ID_EMPLEADO)
        REFERENCES EMPLEADO (ID_EMPLEADO),
    CONSTRAINT FK_MOVIMIENTO_COMPRA FOREIGN KEY (ID_COMPRA)
        REFERENCES COMPRA (ID_COMPRA),
    CONSTRAINT FK_MOVIMIENTO_VENTA FOREIGN KEY (ID_VENTA)
        REFERENCES VENTA (ID_VENTA)
);

COMMIT;
